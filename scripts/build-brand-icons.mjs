// Copies the official Genial Skills artwork into src/app/brand/icons.js:
//   - subject icons (genial-icons.jsx → SUBJECT_SVGS in the Genial Skills project)
//   - navigation-rail icons (nav-icons.js → NAV_RAIL_ICONS) and this
//     dashboard's own NavMenu-icon-*.svg assets
//
//   node scripts/build-brand-icons.mjs "<path to Documents/Genial Skills>"
import fs from 'node:fs'
import path from 'node:path'
import vm from 'node:vm'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const genial = process.argv[2]
if (!genial) throw new Error('Pass the path to the Genial Skills project folder.')

function extractObject(file, marker) {
  const src = fs.readFileSync(path.join(genial, file), 'utf8')
  const start = src.indexOf(marker)
  if (start < 0) throw new Error(`${marker} not found in ${file}`)
  const open = src.indexOf('{', start)
  // Walk to the matching closing brace, skipping template literals.
  let depth = 0
  let inTpl = false
  for (let i = open; i < src.length; i++) {
    const c = src[i]
    if (c === '`') inTpl = !inTpl
    if (inTpl) continue
    if (c === '{') depth++
    if (c === '}' && --depth === 0) return vm.runInNewContext(`(${src.slice(open, i + 1)})`)
  }
  throw new Error(`Unbalanced braces after ${marker}`)
}

const subjects = extractObject('genial-icons.jsx', 'const SUBJECT_SVGS = {')
const rail = extractObject('nav-icons.js', 'window.NAV_RAIL_ICONS = {')

const local = name => fs.readFileSync(path.join(root, 'src/assets', name), 'utf8')
  .replace(/<\?xml[^>]*>/, '')
  .replace(/<title>[\s\S]*?<\/title>/, '')
  .replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, '<svg$1')
  .replace(/<svg([^>]*?)\s(width|height)="[^"]*"/g, '<svg$1')
  .trim()

const nav = {
  home: local('NavMenu-icon-Home.28a18adb10b1606f3726.svg'),
  students: local('NavMenu-icon-Students.4a0ed71e3b1455ec6541.svg'),
  catalog: local('NavMenu-icon-Catalog.cdf34a75cac8cf3bc453.svg'),
  progress: local('NavMenu-icon-Progress.dd0e0a014bbd772a2f18.svg'),
  teams: local('NavMenu-icon-Teams.b60747bd585e71e0e081.svg'),
  planning: rail.homework,
  chat: rail.chat,
}

const out = `// Official Genial Skills artwork — generated by scripts/build-brand-icons.mjs.
// Do not edit by hand.

export const SUBJECT_SVGS = ${JSON.stringify(subjects, null, 2)}

export const NAV_SVGS = ${JSON.stringify(nav, null, 2)}
`
fs.mkdirSync(path.join(root, 'src/app/brand'), { recursive: true })
fs.writeFileSync(path.join(root, 'src/app/brand/icons.js'), out)
console.log('subjects:', Object.keys(subjects).join(', '))
console.log('nav:', Object.keys(nav).join(', '))
for (const [k, v] of Object.entries(subjects)) {
  console.log(k, [...new Set(v.match(/#[0-9A-Fa-f]{6}/g))].slice(0, 5).join(' '))
}
